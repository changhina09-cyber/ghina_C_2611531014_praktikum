nilai_1014 = int(input("Masukkan nilai angka = "))

if nilai_1014 >= 81:
    print("A")
elif nilai_1014 >= 70:
    print("B")
elif nilai_1014 >= 60:
    print("C")
elif nilai_1014 >= 50:
    print("D")
else:
    print("E")
    